export const DICTS: Record<Language, Record<I18nKey, string>> = { zh, en };

export const LANGUAGES: readonly Language[] = ["zh", "en"];

/** `{name}` placeholders are replaced by `params`; missing params stay literal. */
export function translate(
  lang: Language,
  key: I18nKey,
  params?: Record<string, string | number>,
): string {
  const dict = DICTS[lang] ?? DICTS.zh;
  const template: string = dict[key] ?? DICTS.zh[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

export function dictKeys(lang: Language): string[] {
  return Object.keys(DICTS[lang]).sort();
}
